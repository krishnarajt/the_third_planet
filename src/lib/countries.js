/** Any scope can be played with its dependent territories folded in, which
 *  is a different and harder round — so it gets its own id, and therefore
 *  its own score history. */
export const ALL_SUFFIX = '-all';
export const withTerritories = (id, on) =>
  on ? `${baseScope(id)}${ALL_SUFFIX}` : baseScope(id);
export const baseScope = (id) => (id.endsWith(ALL_SUFFIX) ? id.slice(0, -ALL_SUFFIX.length) : id);
export const includesTerritories = (id) => id.endsWith(ALL_SUFFIX);
/** Territories-only is already all territories; there is nothing to add. */
export const canAddTerritories = (id) => baseScope(id) !== 'territories';

export const getCategory = (id) => CATEGORIES.find((c) => c.id === id) ?? CATEGORIES[0];

export function getScope(id) {
  const base = SCOPES.find((s) => s.id === baseScope(id)) ?? SCOPES[0];
  if (!includesTerritories(id)) return base;
  return { ...base, id, label: `${base.label} and its territories` };
}

/** Countries eligible for a given scope. Capitals rounds additionally drop
 *  anything without one, which is most of the uninhabited territories. */
export function poolFor(scopeId, categoryId) {
  const base = baseScope(scopeId);
  const withTerr = includesTerritories(scopeId);
  const sovereign = (c) => c.core || withTerr;

  let pool;
  if (base === 'world') pool = COUNTRIES.filter(sovereign);
  else if (base === 'territories') pool = COUNTRIES.filter((c) => !c.core);
  else pool = COUNTRIES.filter((c) => sovereign(c) && c.region.toLowerCase() === base);

  if (categoryId === 'capitals') pool = pool.filter((c) => c.capital);
  // Nothing without a shape or a marker can ever be clicked, so it must not
  // be asked. Every country has a marker, so this only guards bad data.
  return pool.filter((c) => c.hasShape || POINT_INDEX[c.id] !== undefined);
}

export const flagSrc = (iso) => `/flags/${iso.toLowerCase()}.svg`;

/**
 * The area a round covers, so each question opens framed on the part of the
 * world it is actually about.
 *
 * Built from the middle 90% of the countries' centres rather than their full
 * extents. Russia is filed under Europe and reaches 190 degrees east, so a
 * true bounding box of the region is 220 degrees wide and frames the whole
 * planet — which is no framing at all. Trimming the outliers gives a view of
 * where the region really is; anything left outside is still one pan away,
 * and revealing it flies there regardless.
 *
 * Measured in both the -180..180 and the 0..360 frame, keeping whichever is
 * narrower, or Oceania straddles the dateline and comes out global again.
 */
export function scopeBounds(scopeId, categoryId) {
  // The default view already shows the whole world.
  const base = baseScope(scopeId);
  if (base === 'world' || base === 'territories') return null;

  const pool = poolFor(scopeId, categoryId);
  if (pool.length < 2) return null;

  const span = (values) => {
    const sorted = [...values].sort((a, b) => a - b);
    const cut = Math.floor(sorted.length * 0.05);
    return [sorted[cut], sorted[sorted.length - 1 - cut]];
  };

  const lats = pool.map((c) => c.centre[1]);
  const [s, n] = span(lats);
  const [w, e] = span(pool.map((c) => c.centre[0]));
  const [w2, e2] = span(pool.map((c) => (c.centre[0] < 0 ? c.centre[0] + 360 : c.centre[0])));

  // A little air around the outermost markers so they are not on the edge.
  const pad = 6;
  const box = e - w - (e2 - w2) > 1 ? [w2, s, e2, n] : [w, s, e, n];
  return [box[0] - pad, box[1] - pad, box[2] + pad, box[3] + pad];
}
