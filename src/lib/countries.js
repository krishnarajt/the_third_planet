import data from '../data/countries.json';
import hooks from '../data/hooks.json';
// These two are the bulk of the content (~400 kB combined) and are only
// needed once a country's answer card is actually shown, so they load on
// demand instead of bloating the bundle every page starts with.
let geo = {};
let facts = {};
export const loadDetail = () =>
  Promise.all([import('../data/geoguessr.json'), import('../data/facts.json')]).then(
    ([g, f]) => {
      geo = g.default;
      facts = f.default;
    }
  );
import scripts from '../data/scripts.json';
import fxData from '../../data/fx.json';

/**
 * One merged view of the two data files. countries.json is generated by
 * scripts/build-data.mjs and gets overwritten; hooks.json is written by hand.
 * Keeping them apart means regenerating the geography never eats the prose.
 *
 * The hand-written fields are renamed on the way in: hooks.json calls them
 * flag/hook/capital, and a blind spread would let its `capital` note
 * overwrite the actual name of the capital city.
 */
/** Rebuilt once loadDetail() resolves, so components reading COUNTRIES
 *  before then just see the flag/hook/reference fields — everything the
 *  home screen and the prompt need — and the detail sections appear when
 *  the merge below runs again. */
function buildCountries() {
  return data.countries.map((c) => {
    const h = hooks[c.id] ?? {};
    const g = geo[c.id] ?? {};
    return {
      ...c,
      flagStory: h.flag ?? null,
      hook: h.hook ?? null,
      capitalNote: h.capital ?? null,
      // Street-level identification, for anyone using this to get better at
      // guessing locations from a photo. Every one of these is optional.
      scripts: g.scripts ?? [],
      facts: facts[c.id] ?? [],
      tells: [
        ['Number plates', g.plates],
        ['Roads and signs', g.roads],
        ['Poles and wires', g.poles],
        ['Buildings', g.built],
        ['Landscape', g.nature],
        ['Other giveaways', g.extra],
      ].filter(([, v]) => v),
    };
  });
}

export let COUNTRIES = buildCountries();

/** A dated snapshot of exchange rates, not a live feed — the UI says so. */
export const FX = fxData;

/** Alphabet samples, keyed by the script ids used in geoguessr.json. */
export const SCRIPTS = scripts;
export const getScript = (id) => scripts[id] ?? null;

export let BY_ID = new Map(COUNTRIES.map((c) => [c.id, c]));
export const getCountry = (iso) => BY_ID.get(iso) ?? null;

let detailReady = false;
export function ensureDetail() {
  if (detailReady) return Promise.resolve();
  return loadDetail().then(() => {
    detailReady = true;
    COUNTRIES = buildCountries();
    BY_ID = new Map(COUNTRIES.map((c) => [c.id, c]));
  });
}

